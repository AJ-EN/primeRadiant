import { describe, it, expect } from 'vitest';
import { encodeState, decodeState } from './url';
import {
  ASSUMPTION_COUNT_MAX,
  ASSUMPTION_MAX,
  PAYLOAD_BUDGET,
  SCHEMA_VERSION,
  SENTENCE_MAX,
  type ModelState,
} from './schema';
import { PARAM_KEYS, type Params } from './engine';

/**
 * The v1 wire contract. Read docs/URL-CONTRACT.md before changing anything in this file:
 * a failure here means links already shared have stopped working, and there is no database
 * to migrate them with.
 */

const PARAMS: Params = {
  startingCash: 18000,
  monthlyBurn: 9500,
  customers: 12,
  price: 400,
  churn: 0.08,
  newPerMonth: 2,
};

/**
 * Frozen. Generated once from a fully-populated v1 state and pasted here as a literal, so it
 * is not regenerated by the code it is meant to police. If this stops decoding, a change has
 * broken every link in the wild.
 */
